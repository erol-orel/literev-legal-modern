import logging
import random

from typing import cast

import openai
import tiktoken

from django.conf import settings
from openai import OpenAI

from literev.models import Cluster, Document

# logger
logger = logging.getLogger(__name__)

# openai client
openai_client = OpenAI(api_key=settings.OPENAI_API_KEY)

# gpt model consumed by the api
GPT_MODEL = "gpt-3.5-turbo"

# max tokens accepted by gpt-3.5-turbo model
# openai plan on increasing the max tokens, more info at:
# https://openai.com/blog/new-models-and-developer-products-announced-at-devday
GPT_MODEL_MAX_TOKENS = 4096

# number of tokens reserved for gpt response
MAX_TOKENS_RESPONSE = 250

# 200 tokens extra margin for security
TOKEN_LIMIT = MAX_TOKENS_RESPONSE - MAX_TOKENS_RESPONSE - 200


def call_chatgpt(prompt: str, api_key: str = settings.OPENAI_API_KEY) -> str:
    """
    Call ChatGPT via the OpenAI Python package.

    Sets the OpenAI API key, sends the prompt to ChatGPT,
    and returns the generated response.

    Parameters
    ----------
    prompt : str
        Input text prompt for ChatGPT.

    api_key : str, optional
        The OpenAI API key. Defaults to project settings.

    Returns
    -------
    str
        Response generated by ChatGPT.

    References
    ----------
    More on ChatGPT: https://platform.openai.com/docs/guides/chat/introduction

    Examples
    --------
    >>> response = call_chatgpt("What is the capital of France?")
    >>> print(response)
    'The capital of France is Paris.'
    """

    messages = [{"role": "user", "content": prompt}]

    try:
        logger.info("Sending request to OpenAI ChatGPT API")
        response = openai_client.chat.completions.create(
            model=GPT_MODEL,
            messages=messages,  # type: ignore
            max_tokens=MAX_TOKENS_RESPONSE,
            temperature=0.4,  # this sets the creativity of the response
        )
    except openai.RateLimitError as e:
        if settings.DEBUG:
            logger.debug(f"RateLimitError in dev mode: {e}")
            return "RateLimit Error devmode dummy text"
        else:
            # if not in dev mode, log error and return empty string
            logger.error(f"OpenAI API RateLimitError: {e}")
            return ""
    except openai.OpenAIError as e:
        # all other OpenAI api errors will fall here and return an empty string
        logger.error(f"OpenAI API Error:{e}")
        return ""

    return cast(str, response.choices[0].message.content)


def build_prompt(cluster: Cluster) -> str:
    """
    Build ChatGPT prompt for a scientific topic description.

    Generates a prompt for ChatGPT to describe a scientific topic.
    The prompt follows a specific template, including topic keywords
    extracted from the cluster and relevant related documents for context.

    Parameters
    ----------
    cluster : Cluster
        A Cluster object which contains the topic field with the keywords
        and can also be used for querying related documents.

    Returns
    -------
    str
        Well-constructed ChatGPT prompt.

    Notes
    -----
    The generated prompt is based on a predefined template. It also includes
    constraints for response quality and templates for documents to provide
    context to ChatGPT.

    See Also
    --------
    prompt_template : str
        Base prompt template.
    prompt_constraints : str
        Constraints for response quality.
    document_prompt_template : str
        Template for each document.

    Examples
    --------
    >>> cluster = Cluster.objects.get(id=123)
    >>> prompt = build_prompt(cluster)
    """

    # base prompt used for generating the topic description
    prompt_template = (
        "Provide a succint general description"  # TODO: include or change to clear and concise
        "based on the following most important keywords: {keywords} selected"
        "from a cluster containing case law from the canton of Geneva in Switzerland."
        "The following descriptors for each case law provide additional context:\n\n"
    )

    # constraints can be fine-tuned to prevent unwanted words or sentences
    # this is to prevent unwanted words or sentences

    prompt_constraints = (
        "Ensure the response maintains a narrative voice suitable for general "
        "description while minimizing the use of pronouns. Avoid unnecessary "
        "introductions and redundancies. Avoid using quotes and backticks "
        "Avoid the use of the following keywords and expressions: keyword, "
        "keywords, topic, case, we propose, "
        "proposing, we, this report. Summarize it in two sentences in french language."
    )  # TODO:add Do not include names and not based in one article

    # this template is used for each document
    document_prompt_template = (
        "Document number: {document_number}\n"
        "Descriptor: {document_descriptor}\n"
        "Keywords Sample: {document_abstract}.\n\n"
    )

    # inject topic keyword into prompt
    prompt = prompt_template.format(keywords=cluster.topic)

    # generate encoder based on specific gpt model
    # Change model to gpt o mini
    enc = tiktoken.encoding_for_model(GPT_MODEL)

    # get all documents related to cluster(topic)
    documents = Document.objects.filter(clusterelement__cluster=cluster)

    # calculate initial number of tokens
    tokens_count = len(enc.encode(prompt)) + len(
        enc.encode(prompt_constraints)
    )

    # loop through all documents
    for document_number, document in enumerate(documents, start=1):
        # get document title
        document_descriptor = document.descriptors

        # get document abstract sentences by splitting it on "."
        abstract_words = document.preprocessed_document.split()

        document_abstract = (
            # get 10 random words from preprocessed text
            " ".join(
                random.choices(
                    population=abstract_words, k=27
                )  # TODO: take random adjacent words
            )  # random selection 10 words
            if len(abstract_words) > 10
            else document.preprocessed_document
        )

        # fill the document prompt template with current loop's document data
        document_prompt = document_prompt_template.format(
            document_number=document_number,
            document_descriptor=document_descriptor,
            document_abstract=document_abstract,
        )

        # count number of tokens in the document prompt
        document_tokens = len(enc.encode(document_prompt))

        # update tokens count for the next loop
        tokens_count = tokens_count + document_tokens

        # check if the token limit was reached
        if tokens_count > TOKEN_LIMIT:
            # break the loop without appending the document to the prompt
            break

        # limit not reached, append the document prompt to the 'main' prompt
        prompt = prompt + document_prompt

    # add constraints at the end of the prompt after the loop
    # gpt performs better if we pass the constraints at the end
    prompt = prompt + prompt_constraints
    return prompt


def nlp_topic_description(
    cluster: Cluster, api_key: str = settings.OPENAI_API_KEY
) -> str:
    """
    Generate a topic description based on topic keywords using ChatGPT.

    Parameters
    ----------
    cluster : Cluster
        A Cluster model instance.

    Returns
    -------
    str
        A description generated by ChatGPT based on the input keywords.

    Notes
    -----
    This function returns a dummy text if the application is in development
    mode (DEBUG) and there's no OPENAI_API_KEY configured in the settings.

    Examples
    --------
    >>> input_keywords = ["technology", "innovation", "future"]
    >>> description = nlp_topic_description(input_keywords)
    >>> print(description)
    "This is a dev mode dummy summary text for topic keywords: technology,
    innovation, future"
    """
    if settings.DEBUG and not api_key:
        # returns dummy text if dev mode and there's no openai api key
        return (
            "This is a dev mode dummy summary text for topic keywords: "
            f"{cluster.topic}."  # cluster.topic
        )

    prompt = build_prompt(cluster)

    return call_chatgpt(prompt=prompt, api_key=api_key)
