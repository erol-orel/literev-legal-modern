def get_best_chunk_documents(collection, embedded_query, record_keys):
    """
    Return best ranked chunks sentences given embedded query.
    """
    documents = []
    for record_key in record_keys:
        results = collection.query(
            query_embeddings=embedded_query,
            where={
                "$and": [
                    {"record_key": record_key},
                    {"section": "Mineure-Subsommation"},
                ]
            },
            n_results=8,
            include=["documents"],
        )
        sentences = results.get("documents", [])
        documents.append(sentences[0] if sentences else [])

    return documents


def create_context(documents):
    """
    Create the context from documents senteces for prompt summary.
    """
    ctx = ""
    for idx, sents in enumerate(documents):
        sentences = "\n".join(sents)
        ctx += f"document {idx}:\n{sentences}\n"


def get_cluster_summary(
    cluster: Cluster,
    chamber_name: str,
    question: str,
    api_key: str = settings.HACTAR_API_KEY,
) -> str:
    """
    Return summary for a given cluster.
    """
    if settings.DEBUG and not api_key:
        # returns dummy text if dev mode and there's no openai api key
        return (
            "This is a dev mode dummy summary text for topic keywords: "
            f"{cluster.topic}."
        )
    top_docs = get_top_documents_from_cluster(cluster)

    record_keys = []
    for doc in top_docs:
        record_keys.append(doc.record_key)

    if chamber_name == "chambre_penale":
        collection = chroma_client_penal.get_collection(chamber_name)
    # elif chamber_name == "chambre_administrative":
    #     collection = chroma_client_adm.get_collection(chamber_name)
    else:
        collection = chroma_client.get_collection(chamber_name)

    embedded_query = (
        openai_client.embeddings.create(
            model=EMBEDDING_MODEL, input=[question]
        )
        .data[0]
        .embedding
    )
    documents = get_best_chunk_documents(
        collection, embedded_query, record_keys
    )

    ctx = create_context(documents)
    resp = openai_client.chat.completions.create(
        model=GPT_MODEL,
        messages=[
            {
                "role": "system",
                "content": "Tu es un modèle spécialisé dans l'analyse de jurisprudence suisse.",
            },
            {
                "role": "user",
                "content": PROMPT_CLUSTER_SUMMARY.format(
                    question=question, context=ctx
                ),
            },
        ],
        temperature=0,
    )
    answer = resp.choices[0].message.content
    return answer if answer else ""


def nlp_topic_description(
    cluster: Cluster, api_key: str = settings.HACTAR_API_KEY
) -> str:
    """
    Generate a topic description based on topic keywords using a LLM model.

    Parameters
    ----------
    cluster : Cluster
        A Cluster model instance.

    Returns
    -------
    str
        A description generated by an LLM based on the input keywords.

    Notes
    -----
    This function returns a dummy text if the application is in development
    mode (DEBUG) and there's no HACTAR_KEY configured in the settings.

    Examples
    --------
    >>> input_keywords = ["technology", "innovation", "future"]
    >>> description = nlp_topic_description(input_keywords)
    >>> logger.info(description)
    "This is a dev mode dummy summary text for topic keywords: technology,
    innovation, future"
    """
    if settings.DEBUG and not api_key:
        # returns dummy text if dev mode and there's no openai api key
        return (
            "This is a dev mode dummy summary text for topic keywords: "
            f"{cluster.topic}."
        )

    prompt = build_prompt(cluster, USE_HACTAR_LLM)

    if USE_HACTAR_LLM:
        return call_model(prompt=prompt, api_key=api_key)
    else:
        return call_chatgpt(prompt, api_key=settings.OPENAI_API_KEY)
