def call_model(prompt: str, api_key: str):
    """
    Call chosen LLM model via Open WebUI API endpoints.

    Sets the api_key, sends the prompt to hactar's servers,
    and returns the generated response.

    Parameters
    ----------
    prompt : str
        Input text prompt for LLM.

    api_key : str, optional
        The Open WebUI API key. Defaults to project settings.

    Returns
    -------
    str
        Response generated by LLM.

    References
    ----------
    More on Open WebUI: https://docs.openwebui.com/getting-started/api-endpoints

    Examples
    --------
    >>> response = call_model("What is the capital of France?")
    >>> logger.info(response)
    'The capital of France is Paris.'
    """

    url = "https://hactar.unige.ch/api/chat/completions"
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
    }
    data = {
        "model": f"{LLM_MODEL}",
        "messages": [
            {
                "role": "user",
                "content": prompt,
                "max_tokens": MAX_TOKENS_RESPONSE,
                "temperature": 0.0,
            }
        ],
    }

    try:
        response = requests.post(
            url,
            headers=headers,
            json=data,
            verify=HACTAR_VERIFY_SSL,
        )
        response.raise_for_status()
        result = response.json()

        if "choices" in result and len(result["choices"]) > 0:
            return result["choices"][0]["message"]["content"]
        else:
            logger.error(f"Unexpected API response format: {result}")
            return ""

    except requests.exceptions.RequestException as e:
        logger.error(f"API request failed: {e}")
        return ""
    except json.JSONDecodeError as e:
        logger.error(f"Failed to decode API response: {e}")
        return ""


def call_chatgpt(prompt: str, api_key: str = settings.OPENAI_API_KEY) -> str:
    """
    Call ChatGPT via the OpenAI Python package.

    Sets the OpenAI API key, sends the prompt to ChatGPT,
    and returns the generated response.

    Parameters
    ----------
    prompt : str
        Input text prompt for ChatGPT.

    api_key : str, optional
        The OpenAI API key. Defaults to project settings.

    Returns
    -------
    str
        Response generated by ChatGPT.

    References
    ----------
    More on ChatGPT: https://platform.openai.com/docs/guides/chat/introduction

    Examples
    --------
    >>> response = call_chatgpt("What is the capital of France?")
    >>> logger.info(response)
    'The capital of France is Paris.'
    """

    messages = [{"role": "user", "content": prompt}]

    try:
        logger.info("Sending request to OpenAI ChatGPT API")
        response = openai_client.chat.completions.create(
            model=GPT_MODEL,
            messages=messages,  # type: ignore
            max_tokens=MAX_TOKENS_RESPONSE,
            temperature=0,
        )
    except openai.RateLimitError as e:
        if settings.DEBUG:
            logger.debug(f"RateLimitError in dev mode: {e}")
            return "RateLimit Error devmode dummy text"
        else:
            # if not in dev mode, log error and return empty string
            logger.error(f"OpenAI API RateLimitError: {e}")
            return ""
    except openai.OpenAIError as e:
        # all other OpenAI api errors will fall here and return an empty string
        logger.error(f"OpenAI API Error:{e}")
        return ""

    return cast(str, response.choices[0].message.content)


def build_prompt(cluster: Cluster, USE_HACTAR_LLM: bool) -> str:
    """
    Build a prompt for summarizing a cluster of law cases.

    Constructs a prompt to describe a cluster of law cases based on a predefined
    template. The function collects context from documents associated with the cluster
    and ensures the resulting prompt respects the model's token limit.

    Parameters
    ----------
    cluster : Cluster
        A Cluster object containing the topic and associated documents.

    Returns
    -------
    str
        A complete prompt formatted for LLM consumption.

    Notes
    -----
    - The function selects up to `RANDOM_K` words randomly from each document's preprocessed
      text for inclusion in the prompt.
    - If the token limit (`TOKEN_LIMIT`) is exceeded, additional documents are excluded.
    - Prompts are generated in French and include specific constraints to maintain
      response quality.

    Examples
    --------
    >>> cluster = Cluster.objects.get(id=1)
    >>> prompt = build_prompt(cluster)
    >>> print(prompt)
    """

    prompt_fragments: list[str] = []
    enc = tiktoken.get_encoding(
        cast(
            str, MODEL_SPECS.get(LLM_MODEL, {}).get("encoding", "cl100k_base")
        )
    )

    retrieval_prompt = (
        "You are a legal assistant specialized in generating queries for a RAG system."
        "Your role is to generate a single query in French that will be used to search"
        "a vector database containing legal documents from the canton of Geneva."
        "The following keywords represent the topic of a document cluster:\n{keywords}.\n"
        "Your task is to formulate a RAG query in French that maximizes the relevance of"
        "the search in this context. Your response must be only the"
        "query — no explanation, no commentary, nothing else."
    )

    prompt_template = """
        You are a Swiss lawyer specializing in the analysis of case law from the Geneva Court of Justice.
        Your task is to produce a concise, neutral, and factual summary in a single paragraph of a few sentences,
        based solely on the content of the provided text cluster keywords and additional context.
        Cluster keywords: {keywords}.

        Instructions:
        Do not make any assumptions or add any elements not present in the cluster.

        Identify only:
        the recurring central facts,
        the legal issues examined,
        the legal principles applied,
        the trends or solutions adopted.
        Do not cite any names, full dates, or superfluous details; maintain a sober and formal style.
        The summary should be no more than 4 to 6 sentences, in a single paragraph.

        If the cluster is heterogeneous, summarize the common theme or dominant issues.
        Expected output:
        A single paragraph accurately and concisely summarizing the content of the cluster.

        "In addition to the most important keywords, use "
        "the following additional context coming from the law cases contained in this cluster:"
        "\n"
        """

    prompt_constraints = "Write the response in French."

    cluster_documents = Document.objects.filter(
        clusterelement__cluster=cluster
    )

    doc_num = min(RELEVANT_K, len(cluster_documents))
    # Get the most relevant documents from the cluster
    documents = get_top_documents_from_cluster(cluster, n=doc_num)

    # Generate a better RAG query based on the cluster keywords
    if USE_HACTAR_LLM:
        rag_query = call_model(
            retrieval_prompt.format(keywords=cluster.topic),
            settings.HACTAR_API_KEY,
        )
    else:
        rag_query = call_chatgpt(
            retrieval_prompt.format(keywords=cluster.topic),
            settings.OPENAI_API_KEY,
        )

    logger.info(f"rag_query : {rag_query}")
    prompt = prompt_template.format(keywords=cluster.topic)

    for i, document in enumerate(documents, start=1):
        chunks = prepare_chunks(document.raw_document_text or "")

        retrieval = StringRet(chunks)

        if USE_HACTAR_LLM:
            augmented = cast(
                AugmentedBase,
                HactarAug(
                    api_key=settings.HACTAR_API_KEY,
                    top_k=5,
                    model_name="mxbai-embed-large:latest",  # model_name="nomic-embed-text", # suggested model to embed
                    cache=AUG_CACHE,
                ),
            )

        else:
            augmented = cast(
                AugmentedBase,
                OpenAIAug(
                    api_key=settings.OPENAI_API_KEY,
                    top_k=5,
                    model_name="text-embedding-ada-002",
                    cache=AUG_CACHE,
                ),
            )

        # Getting relevant chunks
        ret_data = retrieval.get(rag_query)
        document_context = augmented.search(rag_query, ret_data)

        # For now only get the chunk which got the best score
        document_context_str = document_context[-1].replace("\n", "")
        logger.info(f"document context : {document_context_str}")

        prompt_fragments.append(f"\ndocument {i} : " + document_context_str)

        if (len(enc.encode(prompt + "".join(prompt_fragments)))) > TOKEN_LIMIT:
            logger.warning(
                "Reached token limit; stopping addition of further documents."
            )
            break

    full_prompt = (
        prompt + "\n".join(prompt_fragments) + "\n" + prompt_constraints
    )
    logger.info(
        f"full prompt ({len(enc.encode(full_prompt))}) : {full_prompt}"
    )

    return full_prompt


